using System;
using System.Collections.Generic;
using System.Linq;

namespace BackBorradorDev;

/// <summary>
/// Genera el formato de bytes usado por las contraseñas legacy de dbo.USUARIOS.
/// </summary>
public static class PasswordLegacyCodec
{
    private const byte Separator = 0x3F;

    private static readonly Dictionary<char, byte[]> Table = new()
    {
        ['0'] = [0xAE, 0xC5], ['1'] = [0xAE, 0xE6], ['2'] = [0xB5, 0xA3],
        ['3'] = [0xB5, 0xB6], ['4'] = [0xB5, 0xA4], ['5'] = [0xB5, 0xA2],
        ['6'] = [0xB5, 0xAE], ['7'] = [0xB5, 0xB5], ['8'] = [0xB5, 0xBB],
        ['9'] = [0xB5, 0xA9], ['a'] = [0xE6, 0xA9], ['b'] = [0xE6, 0xC5],
        ['c'] = [0xE6, 0xE6], ['d'] = [0xB6, 0xA3, 0xA3], ['e'] = [0xB6, 0xA3, 0xB6],
        ['f'] = [0xB6, 0xA3, 0xA4], ['g'] = [0xB6, 0xA3, 0xA2], ['h'] = [0xB6, 0xA3, 0xAE],
        ['i'] = [0xB6, 0xA3, 0xB5], ['j'] = [0xB6, 0xA3, 0xBB], ['k'] = [0xB6, 0xA3, 0xA9],
        ['l'] = [0xB6, 0xA3, 0xC5], ['m'] = [0xB6, 0xA3, 0xE6], ['n'] = [0xB6, 0xB6, 0xA3],
        ['o'] = [0xB6, 0xB6, 0xB6], ['p'] = [0xB6, 0xB6, 0xA4], ['q'] = [0xB6, 0xB6, 0xA2],
        ['r'] = [0xB6, 0xB6, 0xAE], ['s'] = [0xB6, 0xB6, 0xB5], ['t'] = [0xB6, 0xB6, 0xBB],
        ['u'] = [0xB6, 0xB6, 0xA9], ['v'] = [0xB6, 0xB6, 0xC5], ['w'] = [0xB6, 0xB6, 0xE6],
        ['x'] = [0xB6, 0xA4, 0xA3], ['y'] = [0xB6, 0xA4, 0xB6], ['z'] = [0xB6, 0xA4, 0xA4],
        [' '] = [0xA2, 0xA4], ['@'] = [0xBB, 0xAE], ['_'] = [0xE6, 0xB5],
        ['-'] = [0xAE, 0xB5], ['.'] = [0xAE, 0xBB]
    };

    public static bool Matches(string password, byte[]? storedCipherBytes)
    {
        if (storedCipherBytes is null)
            return false;

        var encoded = new List<byte>(password.Length * 4);
        foreach (var rawCharacter in password)
        {
            if (!Table.TryGetValue(char.ToLowerInvariant(rawCharacter), out var value))
                return false;

            encoded.AddRange(value);
            encoded.Add(Separator);
        }

        return encoded.SequenceEqual(storedCipherBytes);
    }
}